-- TASK 6: Calculate the total number of reserved places per trip.

SELECT t.trip_id,
       t.trip_name,
       t.max_places,
       NVL(SUM(r.nb_persons), 0) AS reserved_places
FROM trip t
LEFT JOIN reservation r
    ON r.trip_id = t.trip_id
GROUP BY t.trip_id, t.trip_name, t.max_places
ORDER BY t.trip_id;

