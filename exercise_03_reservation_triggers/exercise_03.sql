    audit_id       NUMBER GENERATED BY DEFAULT AS IDENTITY
                   PRIMARY KEY,
    reservation_id NUMBER,
    operation_type VARCHAR2(10),
    performed_by   VARCHAR2(30),
    operation_date DATE
);

