-- ============================================================
-- CUSTOMER AUDIT TRIGGER
-- Records UPDATE and DELETE operations on CUSTOMERS.
--
-- Run this file in a schema that owns the CUSTOMERS table.
-- The example uses C##OT2, as in the lab instructions.
-- ============================================================

CONNECT c##ot2

-- 1. Create the audit table.
CREATE TABLE audits (
    audit_id         NUMBER GENERATED BY DEFAULT AS IDENTITY
                     PRIMARY KEY,
    table_name       VARCHAR2(255),
    transaction_name VARCHAR2(10),
    by_user          VARCHAR2(30),
    transaction_date DATE
);

-- 2. Create the trigger.
CREATE OR REPLACE TRIGGER customers_audit_trg
AFTER UPDATE OR DELETE ON customers
FOR EACH ROW
DECLARE
    l_transaction VARCHAR2(10);
BEGIN
    l_transaction :=
        CASE
            WHEN UPDATING THEN 'UPDATE'
            WHEN DELETING THEN 'DELETE'
        END;

    INSERT INTO audits (
        table_name,
        transaction_name,
        by_user,
        transaction_date
    )
    VALUES (
        'CUSTOMERS',
        l_transaction,
        USER,
        SYSDATE
    );
END;
/

-- 3. Test an UPDATE.
UPDATE customers
SET credit_limit = 2000
WHERE customer_id = 10;

-- 4. Test a DELETE.
DELETE FROM customers
WHERE customer_id = 10;

-- 5. Display the audit records.
SELECT
    audit_id,
    table_name,
    transaction_name,
    by_user,
    transaction_date
FROM audits
ORDER BY audit_id;

-- 6. Inspect the trigger in the data dictionary.
SELECT
    trigger_name,
    table_name,
    status
FROM user_triggers
WHERE trigger_name = 'CUSTOMERS_AUDIT_TRG';

